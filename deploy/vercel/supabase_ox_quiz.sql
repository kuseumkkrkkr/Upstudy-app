-- Shared OX quiz bank migrated from the legacy SQLite store.
-- Additive only: existing questions are not deleted or rewritten.
begin;

create table if not exists public.ox_quiz_questions (
  id bigint generated by default as identity primary key,
  source_legacy_id bigint unique,
  tag text not null check (length(btrim(tag)) between 1 and 80),
  question text not null check (length(btrim(question)) between 1 and 2000),
  answer boolean not null,
  created_by uuid references public.canary_users(user_id) on delete set null,
  created_at bigint not null check (created_at >= 0),
  unique (tag, question)
);

create index if not exists ox_quiz_questions_tag_created_idx
  on public.ox_quiz_questions(tag, created_at desc, id desc);

alter table public.ox_quiz_questions enable row level security;
revoke all on public.ox_quiz_questions from public, anon, authenticated;
grant select, insert, update, delete on public.ox_quiz_questions to service_role;
grant usage, select on sequence public.ox_quiz_questions_id_seq to service_role;

create or replace function public.insert_ox_quiz_questions(
  p_tag text, p_questions jsonb, p_created_by uuid
) returns integer language plpgsql security definer
set search_path=pg_catalog,public as $$
declare
  item jsonb;
  question_text text;
  current_count integer;
  inserted_count integer := 0;
  changed integer;
begin
  if p_tag is null or length(btrim(p_tag)) not between 2 and 80
     or p_tag !~ '^#'
     or p_questions is null or jsonb_typeof(p_questions) is distinct from 'array'
     or jsonb_array_length(p_questions) not between 1 and 5
     or p_created_by is null then
    raise exception 'invalid_ox_quiz_insert' using errcode='22023';
  end if;
  perform pg_advisory_xact_lock(hashtextextended(lower(p_tag),0));
  select count(*)::integer into current_count from public.ox_quiz_questions
    where lower(tag)=lower(p_tag);
  for item in select value from jsonb_array_elements(p_questions) as values(value) loop
    if jsonb_typeof(item) is distinct from 'object'
       or jsonb_typeof(item->'question') is distinct from 'string'
       or jsonb_typeof(item->'answer') is distinct from 'boolean' then
      raise exception 'invalid_ox_quiz_item' using errcode='22023';
    end if;
    question_text := btrim(item->>'question');
    if length(question_text) not between 1 and 120 then
      raise exception 'invalid_ox_quiz_question' using errcode='22023';
    end if;
    if current_count >= 50 then exit; end if;
    if not exists (
      select 1 from public.ox_quiz_questions
      where lower(tag)=lower(p_tag) and lower(question)=lower(question_text)
    ) then
      insert into public.ox_quiz_questions(tag,question,answer,created_by,created_at)
      values(p_tag,question_text,(item->>'answer')::boolean,p_created_by,extract(epoch from now())::bigint)
      on conflict do nothing;
      get diagnostics changed=row_count;
      inserted_count := inserted_count+changed;
      current_count := current_count+changed;
    end if;
  end loop;
  return inserted_count;
end $$;

revoke all on function public.insert_ox_quiz_questions(text,jsonb,uuid) from public,anon,authenticated;
grant execute on function public.insert_ox_quiz_questions(text,jsonb,uuid) to service_role;

commit;
