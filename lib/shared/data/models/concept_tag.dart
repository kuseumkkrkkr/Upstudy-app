// Concept tag data model.
class ConceptTag {
  final String name;
  final String displayName;
  final List<ConceptTag> children;
  bool isExpanded;
  bool isSelected;

  ConceptTag({
    required this.name,
    required this.displayName,
    this.children = const [],
    this.isExpanded = false,
    this.isSelected = false,
  });

  ConceptTag copyWith({
    String? name,
    String? displayName,
    List<ConceptTag>? children,
    bool? isExpanded,
    bool? isSelected,
  }) {
    return ConceptTag(
      name: name ?? this.name,
      displayName: displayName ?? this.displayName,
      children: children ?? this.children,
      isExpanded: isExpanded ?? this.isExpanded,
      isSelected: isSelected ?? this.isSelected,
    );
  }
}

ConceptTag _group(String name, List<ConceptTag> children) {
  return ConceptTag(name: name, displayName: name, children: children);
}

ConceptTag _tag(String name) {
  return ConceptTag(name: name, displayName: '#$name');
}

